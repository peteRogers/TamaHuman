#!/usr/bin/env python3
"""Turn the student's drawings into TamaHuman/human_sprites.h

Each drawing is a PNG in the sprites/ folder, named after the shape it replaces:
    sprites/1a2b3c4d.png        (the hash printed by capture mode)
    sprites/1a2b3c4d-baby-walk.png   (anything after a dash is just a note)

Black (dark) pixels are drawn as "on" pixels. Transparent pixels count as "off".
Any size is fine; the drawing is placed so its bottom-centre sits where the
original shape's bottom-centre was. Max sensible size: 48x48 at SCALE 3, 64x64 at SCALE 4.

Usage:  python3 tools/make_sprites.py            (needs: pip install pillow)
"""
import pathlib, re, sys
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "sprites"
OUT = ROOT / "TamaHuman" / "human_sprites.h"

entries, arrays = [], []
for png in sorted(SRC.glob("*.png")):
    m = re.match(r"([0-9a-fA-F]{8})", png.stem)
    if not m:
        print(f"skipping {png.name}: name must start with the 8-character hash")
        continue
    h = m.group(1).lower()
    img = Image.open(png).convert("RGBA")
    w, ht = img.size
    if w > 128 or ht > 64:
        sys.exit(f"{png.name} is {w}x{ht}; the screen is only 128x64")
    stride = (w + 7) // 8
    data = bytearray(stride * ht)
    for y in range(ht):
        for x in range(w):
            r, g, b, a = img.getpixel((x, y))
            if a >= 128 and (r + g + b) / 3 < 128:          # opaque and dark = on
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
    name = f"sprite_{h}"
    rows = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
                      for i in range(0, len(data), 16))
    arrays.append(f"// {png.name} ({w}x{ht})\nconst uint8_t {name}[] = {{\n{rows}\n}};\n")
    entries.append(f"  {{0x{h}, {w}, {ht}, {name}}},")
    print(f"added {png.name}  {w}x{ht}")

with open(OUT, "w") as f:
    f.write("// human_sprites.h - GENERATED by tools/make_sprites.py, don't edit by hand.\n")
    f.write("#pragma once\n#include <stdint.h>\n\nnamespace tama {\n\n")
    f.write("\n".join(arrays))
    if entries:
        f.write("\nconst Sprite SPRITES[] = {\n" + "\n".join(entries) + "\n};\n")
        f.write("const int SPRITE_COUNT = sizeof(SPRITES) / sizeof(SPRITES[0]);\n")
    else:
        f.write("const Sprite SPRITES[1] = {{0, 0, 0, nullptr}};\nconst int SPRITE_COUNT = 0;\n")
    f.write("\n}  // namespace tama\n")
print(f"wrote {OUT.relative_to(ROOT)} with {len(entries)} sprite(s)")
