#!/usr/bin/env python3
"""Convert a 12 KB Tamagotchi P1 ROM dump into TamaHuman/tama_rom.h

Usage:  python3 tools/rom_to_header.py path/to/tama.bin
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
if len(sys.argv) < 2:
    sys.exit("usage: python3 tools/rom_to_header.py tama.bin")
data = pathlib.Path(sys.argv[1]).read_bytes()
if len(data) != 12288:
    sys.exit(f"expected 12288 bytes, got {len(data)} - is this the P1 ROM?")
words = [(data[i] & 0x0F) << 8 | data[i + 1] for i in range(0, len(data), 2)]
if max(data[0::2]) > 0x0F:
    sys.exit("bytes look swapped (high byte > 0x0F) - check the file")
lines = [", ".join(f"0x{w:03x}" for w in words[i:i + 16]) for i in range(0, len(words), 16)]
out = ROOT / "TamaHuman" / "tama_rom.h"
out.write_text("// tama_rom.h - GENERATED by tools/rom_to_header.py from the P1 ROM dump\n"
               "#pragma once\n\nstatic const u12_t tama_rom[6144] = {\n  "
               + ",\n  ".join(lines) + "\n};\n")
print(f"wrote {out.relative_to(ROOT)}")
